def knowledge_base_query(topic: str) -> dict:
    """查询知识库"""
    results = []
    topic_lower = topic.lower()

    for key, value in KNOWLEDGE_BASE.items():
        if key.lower() in topic_lower or any(kw in topic for kw in key):
            results.append({"topic": key, **value})

    if not results:
        for key, value in KNOWLEDGE_BASE.items():
            if any(kw in topic_lower for kw in ["保研", "推免", "研究生"]):
                results.append({"topic": key, **value})
                if len(results) >= 3:
                    break

    return {"query": topic, "results": results, "total": len(results)}


def knowledge_base_list() -> list[str]:
    """列出知识库中所有主题"""
    return list(KNOWLEDGE_BASE.keys())
